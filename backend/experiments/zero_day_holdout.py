_MD_TEMPLATE = """# Zero-Day Holdout Experiment

**Research question:** when an attack class the supervised model has *never
seen* hits the stack, does defense collapse — or do the unsupervised layers
hold the line?

## Protocol

| Ingredient | Detail |
|---|---|
| Supervised training set | Legit baseline + ATTACK_1 (voice-clone ATO) + ATTACK_2 (mule ring) + ATTACK_3 (compromised merchant) |
| **Withheld from ALL training** | **ATTACK_4 — CNP high-velocity card testing** |
| Holdout stream (chronological, fresh engine state) | {legit_n} legit transactions, then {zd_n} zero-day transactions |
| Layer attribution (overlapping flags) | XGB: velocity > 0.60 · iForest: anomaly flag · Graph: `ring_detected` |

The zero-day's shape: one bot device + egress IP firing ~$35-$400 ECOM tickets
across dozens of victim cards at 20-60s cadence, mostly skipping 3DS. Every
payload passes the Plausibility Gate by construction — this is operationally
realistic fraud, not garbage input.

## Results

> **The supervised XGBoost model never saw attack 4. It caught {xgb:.0f}%.
> The unsupervised Isolation Forest, trained only on legitimate traffic,
> caught {iff:.0f}% as anomalies**{only_if_clause}. **Overall, the decisioning
> stack stopped {tpr:.0f}% of the zero-day campaign while holding false
> positives on held-out legit traffic to {fpr:.1%}.**

This demonstrates robustness to novel GenAI-powered attacks: attackers can
invent new campaign shapes faster than we can label them, so the defense
cannot depend on supervision alone.

| Layer | Detection rate on zero-day | Notes |
|---|---|---|
| XGBoost (supervised) | {xgb:.0f}% ({xgb_n}/50) | Generalized partially via merchant/device velocity features — no ATTACK_4 rows in training |
| XGBoost at DECLINE threshold (>0.85) | {xgb_strict:.0f}% | Conservative read |
| Isolation Forest (unsupervised, legit-only training) | {iff:.0f}% ({iff_n}/50) | Amount/velocity mix unlike honest checkout traffic |
| EntityGraph (unsupervised) | {graph:.0f}% ({graph_n}/50) | Shared bot device links >=3 victim profiles; warms up after first contacts |
| **DecisionEngine overall (non-APPROVE)** | **{tpr:.0f}% ({caught_n}/50)** | {declined} DECLINED, {stepup} STEP_UP |
| Held-out legit FPR | {fpr:.1%} | Within the <2% budget |

Financial view on the zero-day window alone: **${tp_saved:,.2f} saved**
(declined), **${fn_loss:,.2f} lost** (approved). Transactions flagged *only*
by the Isolation Forest — the pure zero-day catches — are highlighted in
amber in `docs/zero_day_results.png` (txn indices: {only_if}).

## Honest caveats

* Simulated world, synthetic distributions: absolute numbers are directional,
  the ARCHITECTURE claim is the point.
* Layer flags overlap; per-layer rates don't sum to the overall TPR.
* The graph needs 3+ shared-infra contacts before a ring exists — the first
  transactions of any burst are structurally hard.
* One zero-day class was tested. The claim is "the design generalizes to
  unseen classes", demonstrated once, not proven universally.

## Reproduce

```bash
backend/.venv/bin/python backend/experiments/zero_day_holdout.py
```
"""


def _write_md(metrics: dict) -> None:
    zd = metrics["zero_day"]
    det = zd["detected_by"]
    only_if = zd["only_isolation_forest_txns"]
    md = _MD_TEMPLATE.format(
        legit_n=metrics["legit_holdout"]["n"],
        zd_n=zd["n"],
        xgb=det["xgboost_any"] * 100,
        xgb_n=round(det["xgboost_any"] * zd["n"]),
        xgb_strict=det["xgboost_decline_only"] * 100,
        iff=det["isolation_forest"] * 100,
        iff_n=round(det["isolation_forest"] * zd["n"]),
        graph=det["entity_graph"] * 100,
        graph_n=round(det["entity_graph"] * zd["n"]),
        tpr=zd["overall_tpr"] * 100,
        caught_n=round(zd["overall_tpr"] * zd["n"]),
        declined=zd["declined"],
        stepup=zd["step_up"],
        fpr=metrics["legit_holdout"]["fpr"],  # fraction; template formats as %
        tp_saved=zd["tp_saved_usd"],
        fn_loss=zd["fn_loss_usd"],
        only_if=", ".join(map(str, only_if)) or "(none — overlaps with other layers)",
        only_if_clause=(
            f" — with {len(only_if)} transactions caught by NO other layer"
            if only_if else ""
        ),
    )
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    MD_PATH.write_text(md, encoding="utf-8")


if __name__ == "__main__":
    run_experiment()
