def _plot(zd, flags: dict, only_if_idx: list[int], metrics: dict) -> None:
    xs = [i + 1 for i, _ in enumerate(zd)]
    v = [r["scores"]["velocity"] for _, r in zd]
    anom = [r["scores"]["novelty_anomaly"] for _, r in zd]
    graph_hits = [x + 1 for x in range(len(zd)) if flags["graph"][x]]
    decisions = [r["decision"] for _, r in zd]

    fig, ax = plt.subplots(figsize=(13, 6.5))

    # highlight the zero-day catches that ONLY the unsupervised layer found
    for idx in only_if_idx:
        ax.axvspan(idx - 0.45, idx + 0.45, color="#f59e0b", alpha=0.30, zorder=0)

    ax.plot(xs, v, color="#2563eb", lw=2.2, label="XGBoost fraud probability (never saw ATTACK_4)")
    ax.axhline(XGB_FLAG_T, color="#2563eb", ls="--", lw=1, alpha=0.55)
    ax.text(1, XGB_FLAG_T + 0.02, "STEP_UP threshold 0.60", fontsize=8, color="#2563eb")
    ax.axhline(XGB_STRICT_T, color="#1e3a8a", ls=":", lw=1, alpha=0.6)
    ax.text(1, XGB_STRICT_T + 0.02, "DECLINE threshold 0.85", fontsize=8, color="#1e3a8a")

    ax.scatter(graph_hits, [0.04] * len(graph_hits), color="#dc2626", s=55,
               marker="o", zorder=5, label="EntityGraph ring flag")

    ax2 = ax.twinx()
    ax2.plot(xs, anom, color="#059669", lw=1.8, label="Isolation Forest anomaly score (>0 = flagged)")
    ax2.axhline(0, color="#059669", ls="--", lw=1, alpha=0.6)
    ax2.set_ylabel("IF anomaly score (negated decision_function)", color="#059669")
    ax2.tick_params(axis="y", labelcolor="#059669")

    # decision strip along the bottom
    dcolor = {"APPROVE": "#e5e7eb", "STEP_UP": "#fbbf24", "DECLINE": "#ef4444", "MANUAL_REVIEW": "#a78bfa"}
    ax.scatter(xs, [-0.08] * len(xs), c=[dcolor[d] for d in decisions], marker="s", s=42,
               edgecolors="none", zorder=5)

    m = metrics["zero_day"]
    ax.set_title(
        f"Zero-Day Holdout — ATTACK_4 (CNP card-testing) unseen in training\n"
        f"overall catch {m['overall_tpr']:.0%} | XGB {m['detected_by']['xgboost_any']:.0%} | "
        f"iForest {m['detected_by']['isolation_forest']:.0%} | Graph {m['detected_by']['entity_graph']:.0%} | "
        f"legit FPR {metrics['legit_holdout']['fpr']:.1%}",
        fontsize=11,
    )
    ax.set_xlabel("Zero-day transaction index (1-50)")
    ax.set_ylabel("XGBoost fraud probability")
    ax.set_ylim(-0.15, 1.05)
    ax.text(50, -0.115, "bottom strip: decision per txn (grey=approve, amber=step-up, red=decline)",
            ha="right", fontsize=7.5, color="#374151")

    h1, l1 = ax.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    from matplotlib.patches import Patch

    h1.append(Patch(color="#f59e0b", alpha=0.35))
    l1.append(f"caught ONLY by iForest ({len(only_if_idx)} txns)")
    ax.legend(h1 + h2, l1 + l2, loc="upper left", fontsize=8.5, framealpha=0.92)

    fig.tight_layout()
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(PNG_PATH, dpi=150, bbox_inches="tight")
    plt.close(fig)


