"""
ZERO-DAY HOLDOUT EXPERIMENT — the Efficacy-category centerpiece.

Protocol:
  1. Train XGBoost (VelocityScorer) + Isolation Forest on the legit baseline
     and attacks 1-3 ONLY. ATTACK_4 (CNP card-testing velocity burst) is
     generated by its own synthesizer but NEVER enters training.
  2. Replay a chronological stream through ONE fresh-state engine:
       [500 held-out legit txns]  ->  [50 zero-day attack txns]
     The legit segment prices FPR; the attack segment is scored per layer.
  3. Layer attribution per attack txn (independent flags, overlaps allowed):
       XGBoost catch        : velocity score > 0.60 (its intervention zone)
       IsolationForest catch: anomaly flag (predict == -1)
       EntityGraph catch    : ring_detected
  4. Overall TPR for the zero-day = ladder decisions that are not APPROVE.

Outputs:
  docs/zero_day_results.png   per-txn scores + ring flags + only-IF catches
  docs/ZERO_DAY_EXPERIMENT.md narrative with the real numbers filled in
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

BACKEND_ROOT = Path(__file__).resolve().parents[1]
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

import matplotlib

matplotlib.use("Agg")  # headless
import matplotlib.pyplot as plt  # noqa: E402

from data.corpus_builder import build_corpus  # noqa: E402
from defense.decision import APPROVE, DECLINE, STEP_UP, DecisionEngine  # noqa: E402
from defense.novelty import NoveltyDetector  # noqa: E402
from defense.realtime import VelocityScorer  # noqa: E402

DOCS_DIR = BACKEND_ROOT.parent / "docs"
PNG_PATH = DOCS_DIR / "zero_day_results.png"
MD_PATH = DOCS_DIR / "ZERO_DAY_EXPERIMENT.md"

TRAIN_COUNTS = {
    "ATTACK_1_MFA_RESET_VOICE_CLONE": 230,
    "ATTACK_2_SYNTHETIC_MULE_RING": 230,
    "ATTACK_3_PROMPT_INJECTED_MERCHANT": 240,
}
ZERO_DAY_ID = "ATTACK_4_CNP_HIGH_VELOCITY"
LEGIT_HOLDOUT_N = 500
ZD_N = 50
XGB_FLAG_T = 0.60          # velocity score at which the engine intervenes
XGB_STRICT_T = 0.85        # ladder's DECLINE threshold


def _fresh_engine_with_models(trained: DecisionEngine, env) -> DecisionEngine:
    """Same fitted models, brand-new rolling state — eval must not inherit
    the training window's feature history."""
    scorer = VelocityScorer(model_path=None)
    scorer.model = trained.scorer.model
    scorer.model_source = "transferred(fresh state)"
    novelty = NoveltyDetector(model_path=None)
    novelty.model = trained.novelty.model
    novelty.model_source = "transferred(fresh state)"
    return DecisionEngine(environment=env, scorer=scorer, novelty=novelty)


def run_experiment() -> dict:
    # ---- 1. one generation pass => disjoint rows, single consistent world --
    data = build_corpus(
        n_legit=4500 + LEGIT_HOLDOUT_N,
        attack_counts={**TRAIN_COUNTS, ZERO_DAY_ID: ZD_N},
        seed=123,
    )
    rows, env = data["rows"], data["env"]

    legit_rows = sorted((r for r in rows if r["label"] == 0), key=lambda r: r["payload"]["timestamp"])
    train_legit, holdout_legit = legit_rows[:-LEGIT_HOLDOUT_N], legit_rows[-LEGIT_HOLDOUT_N:]
    train_rows = train_legit + [r for r in rows if r["attack_id"] in TRAIN_COUNTS]
    zd_rows = sorted((r for r in rows if r["attack_id"] == ZERO_DAY_ID), key=lambda r: r["payload"]["timestamp"])

    assert zd_rows and all(r["attack_id"] == ZERO_DAY_ID for r in zd_rows)
    assert not any(r["attack_id"] == ZERO_DAY_ID for r in train_rows), "zero-day leaked into training!"

    # ---- 2. train the stack on attacks 1-3 only ----------------------------
    trainer = DecisionEngine(environment=env)
    train_metrics = trainer.train(train_rows)

    # ---- 3. replay holdout stream through fresh state ----------------------
    engine = _fresh_engine_with_models(trainer, env)
    records = []
    for r in sorted(holdout_legit + zd_rows, key=lambda r: r["payload"]["timestamp"]):
        rec = engine.decide(r["payload"])
        rec["attack_id"] = r["attack_id"]
        records.append(rec)

    # ---- 4. metrics ----------------------------------------------------------
    def layer_flags(rec: dict) -> dict:
        s = rec["scores"]
        return {
            "xgb": s["velocity"] > XGB_FLAG_T,
            "xgb_strict": s["velocity"] > XGB_STRICT_T,
            "iforest": bool(s["is_anomaly"]),
            "graph": bool(s["ring_detected"]),
        }

    legit_recs = [r for r in records if r["attack_id"] == "LEGIT"]
    fpr = sum(1 for r in legit_recs if r["decision"] != APPROVE) / max(len(legit_recs), 1)

    zd = [(i, r) for i, r in enumerate(records) if r["attack_id"] != "LEGIT"]
    n_zd = len(zd)
    flags = {name: [layer_flags(r)[name] for _, r in zd] for name in ("xgb", "xgb_strict", "iforest", "graph")}
    caught = [r["decision"] != APPROVE for _, r in zd]
    only_if_idx = [
        x + 1 for x in range(n_zd)
        if flags["iforest"][x] and not flags["xgb"][x] and not flags["graph"][x]
    ]

    zd_pairs = list(zd)
    metrics = {
        "train": {
            **train_metrics,
            "zero_day_in_training": False,
            "train_legit_rows": len(train_legit),
            "train_attack_rows": len(train_rows) - len(train_legit),
        },
        "legit_holdout": {"n": len(legit_recs), "fpr": round(fpr, 4)},
        "zero_day": {
            "n": n_zd,
            "overall_tpr": round(sum(caught) / n_zd, 4),
            "declined": sum(
                1 for (_, r) in zd_pairs if r["decision"] == DECLINE
            ),
            "step_up": sum(1 for (_, r) in zd_pairs if r["decision"] == STEP_UP),
            "detected_by": {
                "xgboost_any": round(sum(flags["xgb"]) / n_zd, 4),
                "xgboost_decline_only": round(sum(flags["xgb_strict"]) / n_zd, 4),
                "isolation_forest": round(sum(flags["iforest"]) / n_zd, 4),
                "entity_graph": round(sum(flags["graph"]) / n_zd, 4),
            },
            "only_isolation_forest_txns": only_if_idx,
            "fn_loss_usd": round(sum(r["amount"] for (_, r), c in zip(zd, caught) if not c), 2),
            "tp_saved_usd": round(sum(r["amount"] for (_, r), c in zip(zd, caught) if c and r["decision"] == DECLINE), 2),
        },
    }

    _plot(zd, flags, only_if_idx, metrics)
    _write_md(metrics)
    print(json.dumps(metrics, indent=2))
    return metrics


